function export_swingup(swingup)
% Run mini_cuboid_swingup_ini, then export_swingup(swingup).
% Generate include/swingup_trajectory.h and rebuild with PlatformIO.
% Keep MATLAB Ts and the firmware Ts in src/main.cpp equal.
% Export N interval-averaged torques; omit MATLAB's terminal hold sample.

    torque = single(swingup.commands.torque(1:end-1));
    N = numel(torque);
    assert(isa(torque, 'single') && isvector(torque) && N >= 1 && N <= 65535);
    assert(isfinite(swingup.param.km) && swingup.param.km > 0);
    assert(all(isfinite(torque)) && all(abs(double(torque)/swingup.param.km) <= 15), ...
        'Torque commands must be finite and within the firmware current limit.');
    assert(isfinite(swingup.omega2_0) && swingup.omega2_0 > 0);

    project_dir = fileparts(fileparts(fileparts(mfilename('fullpath'))));
    header = fullfile(project_dir, 'include', 'swingup_trajectory.h');
    fid = fopen(header, 'w');
    assert(fid ~= -1, 'Cannot open generated header: %s', header);
    close_file = onCleanup(@() fclose(fid));
    fprintf(fid, '#pragma once\n\n#include <cstdint>\n\n');
    fprintf(fid, '// Generated by MATLAB export_swingup(swingup); do not edit values manually.\n');
    fprintf(fid, '// Interval-averaged torques [Nm]; Ts = %.9g s, matching src/main.cpp.\n', swingup.Ts);
    fprintf(fid, 'constexpr float swingup_omega2_0 = %.9ef; // rad/s, relative to body\n', swingup.omega2_0);
    fprintf(fid, 'constexpr float swingup_torque_Nm[] = {\n');
    for k = 1:N
        % Ten significant digits preserve each single-precision torque.
        fprintf(fid, '    %.9ef,\n', torque(k));
    end
    fprintf(fid, '};\n');
    fprintf(fid, 'constexpr uint16_t swingup_sample_count = sizeof(swingup_torque_Nm) / sizeof(swingup_torque_Nm[0]);\n');
    fprintf('Exported %d torque intervals to %s\n', N, header);
end
